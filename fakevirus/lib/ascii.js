const BLOCK = '█';
const SPACE = ' ';

/** Tekst groot zetten door elke pixel meerdere blokken te maken. */
export function renderBig(text, { scale = 2, color = null, stream = null } = {}) {
  const lines = render(text, { scale });
  return lines.map((line) => (color ? `${color}${line}${'\x1b[0m'}` : line));
}

/** Returns een array van string-lines. */
export function render(text, { scale = 2, char = BLOCK } = {}) {
  const chars = String(text).toUpperCase().split('');
  const rows = 7;
  const out = [];
  for (let r = 0; r < rows; r += 1) {
    let line = '';
    for (const ch of chars) {
      const glyph = FONT[ch] || FONT[' '];
      for (let c = 0; c < glyph[r].length; c += 1) {
        line += glyph[r][c] === '#' ? char : SPACE;
      }
      line += SPACE.repeat(scale);
    }
    for (let s = 1; s < scale; s += 1) out.push(line);
    out.push(line);
  }
  return out;
}

/** Breedte van een gerenderde tekst (zonder kleur). */
export function renderWidth(text, scale = 2) {
  const chars = String(text).toUpperCase();
  return chars.length * (5 + scale);
}

/** Centreert een gerenderde tekst in een area van `width` kolommen. */
export function centerRender(text, width, scale = 2) {
  const lines = render(text, { scale });
  const pad = (line) => {
    const missing = Math.max(0, Math.floor((width - line.length) / 2));
    return ' '.repeat(missing) + line;
  };
  return lines.map(pad);
}

/** Tekent een box met een titel. */
export function box(title, lines, width = 78) {
  const out = [];
  const label = title ? ` ${title} ` : '';
  const pad = width - label.length - 2;
  const top = `┌${label}${'─'.repeat(Math.max(0, pad))}┐`;
  const bottom = `└${'─'.repeat(width - 2)}┘`;
  out.push(top);
  for (const line of lines) {
    const body = String(line);
    const len = visibleLength(body);
    out.push(`│ ${body}${' '.repeat(Math.max(0, width - len - 3))}│`);
  }
  out.push(bottom);
  return out;
}

